    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        try {
            String dni = new String(pwdDni.getPassword()).trim();
            Paciente paciente = gestor.buscarPacientePorDni(dni)
                    .orElseThrow(() -> new IllegalArgumentException("No hay un paciente registrado con ese DNI."));

            List<Cita> citas = gestor.getCitasDePaciente(paciente);
            String listaCitas = citas.isEmpty()
                    ? "Sin citas programadas."
                    : citas.stream()
                            .map(c -> " - " + c)
                            .collect(Collectors.joining("\n"));

            areaResultado.setText(paciente.obtenerResumen() + "\n\nCitas:\n" + listaCitas);
            mostrarExito("Paciente encontrado. Citas: " + citas.size());
        } catch (IllegalArgumentException e) {
            areaResultado.setText("");
            mostrarError(e.getMessage());
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

