    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        try {
            String nombre = txtNombre.getText().trim();
            String dni = new String(pwdDni.getPassword()).trim();
            String telefono = txtTelefono.getText().trim();

            Paciente nuevo;
            if (chkMenor.isSelected()) {
                int edad = Integer.parseInt(txtEdad.getText().trim());
                nuevo = new PacienteNino(nombre, dni, telefono, edad, txtApoderado.getText());
            } else {
                nuevo = new PacienteAdulto(nombre, dni, telefono, txtOcupacion.getText());
            }
            gestor.registrarPaciente(nuevo);
            lblMensaje.setText("Paciente registrado correctamente " );
            limpiarCampos();
        } catch (NumberFormatException e) {
            lblMensaje.setText("La edad debe ser un número entero.");
        } catch (IllegalArgumentException e) {
            lblMensaje.setText(e.getMessage());
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

