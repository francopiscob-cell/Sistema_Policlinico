    /**
     * Busca al paciente por el DNI escrito; falla si no está registrado.
     */
    private Paciente leerPaciente() {
        String dni = new String(pwdDni.getPassword()).trim();
        return gestor.buscarPacientePorDni(dni)
                .orElseThrow(() -> new IllegalArgumentException("No hay un paciente registrado con ese DNI."));
    }

    /**
     * Lee la fecha y la hora; rechaza formatos incorrectos y fechas pasadas.
     */
    private LocalDateTime leerFechaHora() {
        LocalDateTime fechaHora;
        try {
            LocalDate fecha = LocalDate.parse(txtFecha.getText().trim(), FORMATO_FECHA);
            LocalTime hora = LocalTime.parse(txtHora.getText().trim(), FORMATO_HORA);
            fechaHora = LocalDateTime.of(fecha, hora);
        } catch (DateTimeParseException e) {
            throw new IllegalArgumentException("Use el formato dd/MM/aaaa para la fecha y HH:mm para la hora.");
        }
        if (fechaHora.isBefore(LocalDateTime.now())) {
            throw new IllegalArgumentException("La fecha y hora deben ser posteriores a la actual.");
        }
        return fechaHora;
    }

    private void mostrarExito(String mensaje) {
        txtMensaje.setForeground(new java.awt.Color(0, 128, 0));
        txtMensaje.setText(mensaje);
    }

    private void mostrarError(String mensaje) {
        txtMensaje.setForeground(java.awt.Color.RED);
        txtMensaje.setText(mensaje);
    }

    /**
     * Llena la lista desplegable con las citas del paciente.
     */
    private void mostrarCitasDe(Paciente paciente) {
        citasEncontradas = gestor.getCitasDePaciente(paciente);
        String[] textos = citasEncontradas.stream()
                .map(Cita::toString)
                .toArray(String[]::new);
        cmbCitas6.setModel(new DefaultComboBoxModel<>(textos));
    }

    private Cita citaSeleccionada() {
        int indice = cmbCitas6.getSelectedIndex();
        if (indice < 0 || indice >= citasEncontradas.size()) {
            throw new IllegalArgumentException("Primero busque las citas y elija una.");
        }
        return citasEncontradas.get(indice);
    }

